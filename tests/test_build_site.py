"""Showcase data: built from saved results only (no API), every quote located, honest run labels."""
import json

import pytest

from scripts import build_site


@pytest.fixture(scope="module")
def data():
    return build_site.build()


def test_every_report_and_quote_is_present(data):
    assert [r["id"] for r in data["reports"]] == [f"report_{i:02d}" for i in range(1, 11)]
    assert all(r["unlocated"] == [] for r in data["reports"])
    assert {r["id"] for r in data["requirements"]} == {"R1", "R2", "R3", "R4", "R5"}


def test_segments_rebuild_the_report_text(data):
    def flat(segs):
        return "".join(s["t"] if "t" in s else flat(s["k"]) for s in segs)
    for r in data["reports"]:
        assert flat(r["segments"]) == r["text"]


def test_runs_are_labelled_frozen_or_earlier(data):
    cfg = data["config"]
    for r in data["reports"]:
        assert r["run"]["frozen"] == (r["run"]["prompt_version"] == cfg["prompt_version"])
    assert cfg["tag"] == "v1.0-frozen"


def test_memo_and_answer_key(data):
    r2 = next(r for r in data["reports"] if r["id"] == "report_02")
    assert r2["memo"].startswith("# Review: report_02")
    assert {p["target"] for p in r2["answer_key"]["planted"]} == {"13.4%", "exceed 50%"}


def test_heldout_is_a_placeholder_until_it_exists(data):
    assert data["heldout"] is None


def test_profile_links(data):
    assert data["links"]["linkedin"] == "https://www.linkedin.com/in/eytan-berkowitz"
    assert data["links"]["github"] == "https://github.com/eytanberko/report-checker"


def test_main_writes_loadable_js(tmp_path, monkeypatch):
    out = tmp_path / "site.js"
    monkeypatch.setattr(build_site, "OUT", out)
    monkeypatch.setattr(build_site, "ROOT", tmp_path)
    assert build_site.main() == 0
    text = out.read_text(encoding="utf-8")
    assert text.startswith("// Generated by scripts/build_site.py")
    payload = json.loads(text[text.index("=") + 1:].rstrip().rstrip(";"))
    assert len(payload["reports"]) == 10


def test_frozen_needs_the_prompts_and_both_models():
    cfg = {"prompt_version": "p1", "model": "lite", "judge_model": "flash"}
    assert build_site.is_frozen(dict(cfg), cfg)
    assert not build_site.is_frozen({**cfg, "judge_model": "lite"}, cfg)
    assert not build_site.is_frozen({"prompt_version": "p1"}, cfg)  # older results without model meta


def test_earlier_run_label_clears_itself_when_a_report_is_rerun_frozen(tmp_path, monkeypatch, data):
    """Tomorrow's run writes results with the frozen meta; the next build marks those reports frozen."""
    import shutil

    import yaml
    for p in (build_site.RESULTS).glob("report_*.json"):
        shutil.copy(p, tmp_path / p.name)
    rep = next(r for r in yaml.safe_load((build_site.BENCH / "reports.yaml").read_text(encoding="utf-8"))["reports"]
               if r["id"] == "report_07")
    saved = json.loads((tmp_path / "report_07.json").read_text(encoding="utf-8"))
    monkeypatch.setattr(build_site, "RESULTS", tmp_path)
    cfg = build_site.frozen_config()
    assert build_site.report_entry(rep, cfg)["run"]["frozen"] is False          # today: earlier run
    saved["meta"] = {**cfg, "finished": "tomorrow"}                              # what evaluate.py writes
    (tmp_path / "report_07.json").write_text(json.dumps(saved), encoding="utf-8")
    assert build_site.report_entry(rep, cfg)["run"]["frozen"] is True           # label gone, no manual edit
